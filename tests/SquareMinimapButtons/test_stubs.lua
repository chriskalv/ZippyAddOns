-- Self-test of the stubs that the next packages rely on: parent chain and visibility, events,
-- timers (also through AceTimer and AceEvent), switches of the simulated client.

describe("frames", function()
    it("IsVisible follows the parent chain, IsShown does not", function()
        ReloadAddon({})
        local bar = CreateFrame("Frame", "TestBar", UIParent)
        local button = CreateFrame("Button", "TestButton", Minimap)
        button:SetParent(bar)
        bar:Hide()
        assert_true(button:IsShown())
        assert_false(button:IsVisible())
        bar:Show()
        assert_true(button:IsVisible())
        assert_true(_G.TestButton == button, "named frames are globals")
    end)

    it("keeps children, regions, points, sizes, strata and levels", function()
        ReloadAddon({})
        local button = CreateFrame("Button", nil, Minimap)
        local icon = button:CreateTexture(nil, "ARTWORK")
        button:SetSize(22, 22)
        button:SetPoint("TOPLEFT", Minimap, "TOPLEFT", 1, -1)
        button:SetFrameStrata("HIGH")
        button:SetFixedFrameStrata(true)
        button:SetFrameStrata("LOW")
        local children = { Minimap:GetChildren() }
        assert_true(children[#children] == button)
        assert_true(({ button:GetRegions() })[1] == icon)
        assert_eq({ button:GetSize() }, { 22, 22 })
        assert_eq({ button:GetPoint() }, { "TOPLEFT", Minimap, "TOPLEFT", 1, -1 })
        assert_eq(button:GetFrameStrata(), "HIGH", "fixed strata ignores SetFrameStrata")
        assert_eq(button:GetObjectType(), "Button")
        assert_true(button:IsObjectType("Frame"))
        assert_eq(icon:GetObjectType(), "Texture")
    end)

    it("runs and hooks scripts", function()
        ReloadAddon({})
        local frame = CreateFrame("Frame", nil, UIParent)
        local log = {}
        frame:SetScript("OnEnter", function() log[#log + 1] = "script" end)
        frame:HookScript("OnEnter", function() log[#log + 1] = "hook" end)
        frame:GetScript("OnEnter")(frame)
        assert_eq(log, { "script", "hook" })
    end)

    it("has the Forever minimap frames", function()
        ReloadAddon({})
        assert_true(Minimap:GetParent() == MinimapCluster.MinimapContainer)
        assert_eq(MinimapCluster.Tracking.Button:GetObjectType(), "DropdownButton")
        assert_true(MinimapCluster.IndicatorFrame.MailFrame ~= nil)
        assert_true(GameTimeFrame ~= nil)
        assert_nil(GameTimeTexture, "no GameTimeTexture in Forever")
        assert_true(QueueStatusButton ~= nil)
    end)
end)

describe("events and timers", function()
    it("fires events to registered frames until they unregister", function()
        ReloadAddon({})
        local frame = CreateFrame("Frame")
        local got = {}
        frame:SetScript("OnEvent", function(_, event, arg) got[#got + 1] = event .. ":" .. tostring(arg) end)
        frame:RegisterEvent("UPDATE_PENDING_MAIL")
        FireEvent("UPDATE_PENDING_MAIL", 1)
        frame:UnregisterEvent("UPDATE_PENDING_MAIL")
        FireEvent("UPDATE_PENDING_MAIL", 2)
        assert_eq(got, { "UPDATE_PENDING_MAIL:1" })
    end)

    it("runs C_Timer callbacks in order of due time", function()
        ReloadAddon({})
        local log = {}
        C_Timer.After(2, function() log[#log + 1] = "b" end)
        C_Timer.After(1, function() log[#log + 1] = "a" end)
        local ticker = C_Timer.NewTicker(1.5, function() log[#log + 1] = "t" end)
        AdvanceTime(3.1)
        ticker:Cancel()
        AdvanceTime(10)
        assert_eq(log, { "a", "t", "b", "t" })
        assert_near(GetTime(), 13.1)
    end)

    it("AceTimer and AceEvent work on the stubs", function()
        ReloadAddon({})
        StartClient()
        local SMB = GetAddon()
        local ticks, events = 0, 0
        SMB.Tick = function() ticks = ticks + 1 end
        SMB.UPDATE_PENDING_MAIL = function() events = events + 1 end
        SMB:ScheduleRepeatingTimer("Tick", 6)
        SMB:RegisterEvent("UPDATE_PENDING_MAIL")
        AdvanceTime(18.5)
        FireEvent("UPDATE_PENDING_MAIL")
        assert_eq(ticks, 3)
        assert_eq(events, 1)
    end)
end)

describe("client switches", function()
    it("combat, pet battle and mail come from the configuration", function()
        ReloadAddon({ combat = true, petBattle = true, newMail = true })
        assert_true(InCombatLockdown())
        assert_true(C_PetBattles.IsInBattle())
        assert_true(HasNewMail())
