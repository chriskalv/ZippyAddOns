end)

describe("minimap test buttons", function()
    it("the Forever minimap has ZoomHitArea, ZoomIn, ZoomOut and MinimapBackdrop as children", function()
        ReloadAddon({})
        local children = { Minimap:GetChildren() }
        assert_eq(#children, 4)
        assert_true(children[1] == Minimap.ZoomHitArea and children[2] == Minimap.ZoomIn)
        assert_true(children[3] == Minimap.ZoomOut and children[4] == MinimapBackdrop)
        assert_eq(Minimap.ZoomHitArea:GetObjectType(), "Frame")
        assert_eq(MinimapBackdrop:GetObjectType(), "Frame")
        assert_eq(Minimap.ZoomIn:GetObjectType(), "Button")
        assert_nil(Minimap.ZoomIn:GetName())
        assert_nil(Minimap.ZoomIn.icon)
    end)

    it("builds a LibDBIcon button like LibDBIcon-1.0", function()
        ReloadAddon({})
        local button = NewLibDBIconButton("Test")
        assert_true(_G.LibDBIcon10_Test == button)
        assert_true(button:GetParent() == Minimap)
        assert_eq(button:GetFrameStrata(), "MEDIUM")
        assert_eq(button:GetFrameLevel(), 8)
        assert_true(button:HasFixedFrameStrata() and button:HasFixedFrameLevel())
        assert_eq(StubState(button).dragButtons, { "LeftButton" })
        assert_eq(button:GetHighlightTexture():GetTextureFileID(), 136477)
        assert_eq(button.border:GetTextureFileID(), 136430)
        assert_eq(button.background:GetTextureFileID(), 136467)
        assert_eq({ button.icon:GetTexCoord() }, { 0.05, 0.05, 0.05, 0.95, 0.95, 0.05, 0.95, 0.95 })
        assert_eq(select("#", button:GetRegions()), 4)
    end)

    it("builds one named pin per kind and the unnamed buttons", function()
        ReloadAddon({})
        for _, kind in ipairs(PIN_KINDS) do
            local pin = NewMinimapPin(kind)
            assert_true(pin:GetName() ~= nil, kind)
            assert_true(pin:GetParent() == Minimap, kind)
        end
        assert_nil(NewUnnamedButton(false).icon)
        assert_true(NewUnnamedButton(true).icon ~= nil)
    end)

    it("reports secret texture coordinates through issecretvalue", function()
        ReloadAddon({})
        local plain = NewPlainButton("Plain")
        local secret = NewPlainButton("Secret")
        MarkSecretTexCoord(secret.icon)
        assert_false(issecretvalue((plain.icon:GetTexCoord())))
        assert_true(issecretvalue((secret.icon:GetTexCoord())))
        assert_false(issecretvalue((plain.icon:GetTexCoord())), "the next call clears the mark")
        assert_false(issecretvalue("text"))
        ReloadAddon({ noSecretAPI = true })
        assert_nil(issecretvalue)
    end)

    it("SetTexture() without argument clears the texture and is recorded", function()
        ReloadAddon({})
        local texture = UIParent:CreateTexture(nil, "ARTWORK")
        texture:SetTexture(136430)
        assert_eq(StubState(texture).setTextureArgs, 1)
        texture:SetTexture()
        assert_nil(texture:GetTexture())
        assert_eq(StubState(texture).setTextureArgs, 0)
    end)
end)
