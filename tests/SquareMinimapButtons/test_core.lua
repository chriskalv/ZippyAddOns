-- Core helpers ported from ProjectAzilroka's Init.lua: TexCoords, SetTemplate, CreateShadow,
-- SetInside, class color.

describe("TexCoords", function()
    it("crops 0.08 per side without ElvUI", function()
        ReloadAddon({})
        local SMB = GetAddon()
        local l, r, t, b = SMB:TexCoords()
        assert_near(l, 0.08)
        assert_near(r, 0.92)
        assert_near(t, 0.08)
        assert_near(b, 0.92)
        local packed = SMB:TexCoords(true)
        assert_eq(#packed, 4)
        assert_near(packed[2], 0.92)
    end)

    it("follows ElvUI's general.cropIcon", function()
        ReloadAddon({ elvui = { cropIcon = 1 } })
        local l, r = GetAddon():TexCoords()
        assert_near(l, 0.04)
        assert_near(r, 0.96)
        ReloadAddon({ elvui = { cropIcon = 0 } })
        l, r = GetAddon():TexCoords()
        assert_near(l, 0)
        assert_near(r, 1)
    end)

    it("uses 2 when ElvUI has no cropIcon", function()
        ReloadAddon({ elvui = {} })
        assert_near((GetAddon():TexCoords()), 0.08)
    end)
end)

describe("SetTemplate", function()
    it("without ElvUI and AddOnSkins: own backdrop, black border, dark fill", function()
        ReloadAddon({})
        local frame = CreateFrame("Frame", nil, UIParent)
        GetAddon():SetTemplate(frame)
        assert_eq(frame.backdropInfo, { bgFile = [[Interface\Buttons\WHITE8X8]], edgeFile = [[Interface\Buttons\WHITE8X8]], edgeSize = 1 })
        assert_eq({ frame:GetBackdropColor() }, { 0.08, 0.08, 0.08, 0.8 })
        assert_eq({ frame:GetBackdropBorderColor() }, { 0, 0, 0, 1 })
    end)

    it("mixes BackdropTemplateMixin into frames without SetBackdrop only once", function()
        ReloadAddon({})
        local SMB = GetAddon()
        local frame = CreateFrame("Button", nil, UIParent)
        assert_nil(frame.SetBackdrop)
        SMB:SetTemplate(frame)
        local setBackdrop = frame.SetBackdrop
        assert_eq(type(setBackdrop), "function")
        SMB:SetTemplate(frame)
        assert_true(frame.SetBackdrop == setBackdrop)
    end)

    it("with ElvUI's frame API: SetTemplate('Transparent', true)", function()
        ReloadAddon({ elvui = { frameAPI = true } })
        local frame = CreateFrame("Frame", nil, UIParent)
        GetAddon():SetTemplate(frame)
        assert_eq(StubState(frame).elvTemplate, { "Transparent", true })
        assert_nil(frame.backdropInfo, "no own backdrop")
    end)

    it("with AddOnSkins: AddOnSkins[1]:SetTemplate", function()
        ReloadAddon({ addonskins = true, elvui = { frameAPI = true } })
        local frame = CreateFrame("Frame", nil, UIParent)
        GetAddon():SetTemplate(frame)
        assert_eq(STUB.calls.AddOnSkinsSetTemplate, 1)
        assert_nil(STUB.calls.ElvUISetTemplate)
    end)
end)

describe("CreateShadow", function()
    it("does nothing without ElvUI, Tukui or AddOnSkins", function()
        ReloadAddon({})
        local frame = CreateFrame("Frame", nil, UIParent)
        GetAddon():CreateShadow(frame)
        assert_nil(StubState(frame).shadow)
        assert_nil(STUB.calls.AddOnSkinsCreateShadow)
    end)

    it("uses the frame's CreateShadow (ElvUI) or AddOnSkins", function()
        ReloadAddon({ elvui = { frameAPI = true } })
        local frame = CreateFrame("Frame", nil, UIParent)
        GetAddon():CreateShadow(frame)
        assert_true(StubState(frame).shadow)
        ReloadAddon({ addonskins = true })
        GetAddon():CreateShadow(CreateFrame("Frame", nil, UIParent))
        assert_eq(STUB.calls.AddOnSkinsCreateShadow, 1)
    end)
end)

describe("SetInside", function()
    it("anchors 1 pixel inside the parent by default", function()
        ReloadAddon({})
        local parent = CreateFrame("Frame", nil, UIParent)
        local texture = parent:CreateTexture(nil, "ARTWORK")
        texture:SetPoint("CENTER")
        GetAddon():SetInside(texture)
        assert_eq(texture:GetNumPoints(), 2)
        assert_eq({ texture:GetPoint(1) }, { "TOPLEFT", parent, "TOPLEFT", 1, -1 })
        assert_eq({ texture:GetPoint(2) }, { "BOTTOMRIGHT", parent, "BOTTOMRIGHT", -1, 1 })
    end)

    it("takes an anchor and offsets", function()
        ReloadAddon({})
        local anchor = CreateFrame("Frame", nil, UIParent)
        local frame = CreateFrame("Frame", nil, UIParent)
        GetAddon():SetInside(frame, anchor, 2, 3)
        assert_eq({ frame:GetPoint(1) }, { "TOPLEFT", anchor, "TOPLEFT", 2, -3 })
        assert_eq({ frame:GetPoint(2) }, { "BOTTOMRIGHT", anchor, "BOTTOMRIGHT", -2, 3 })
    end)
end)

describe("class color", function()
    it("takes the player's class from RAID_CLASS_COLORS", function()
        ReloadAddon({ player = { class = "MAGE" } })
        local c = RAID_CLASS_COLORS.MAGE
        assert_eq(GetAddon().ClassColor, { c.r, c.g, c.b })
    end)

    it("prefers CUSTOM_CLASS_COLORS and falls back to PRIEST", function()
        ReloadAddon({})
        local SMB = GetAddon()
        CUSTOM_CLASS_COLORS = { MAGE = { r = 0.1, g = 0.2, b = 0.3 } }
        assert_eq(SMB:GetClassColor("MAGE"), { r = 0.1, g = 0.2, b = 0.3 })
        CUSTOM_CLASS_COLORS = nil
        assert_true(SMB:GetClassColor(nil) == RAID_CLASS_COLORS.PRIEST)
    end)
end)

